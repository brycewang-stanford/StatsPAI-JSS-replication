#!/usr/bin/env python3
"""Generate the six-design DML PLR coverage table (Section 5).

Reads ``replication/results/dml_plr_designs.json``, written by
``dml_plr_designs.py``, and writes ``manuscript/tables/dml_plr_designs.tex``.
``--check`` fails when the committed table differs from the stored results.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

_SCRIPTS_DIR = str(Path(__file__).resolve().parent)
if _SCRIPTS_DIR not in sys.path:
    sys.path.insert(0, _SCRIPTS_DIR)

from _paths import PAPER_ROOT  # noqa: E402

SRC = PAPER_ROOT / "replication" / "results" / "dml_plr_designs.json"
OUT = PAPER_ROOT / "manuscript" / "tables" / "dml_plr_designs.tex"
LABELS = {
    "smooth2": ("Smooth surface", 2),
    "linear10": ("Exactly linear", 10),
    "sparse50": ("Sparse linear, correlated", 50),
    "logistic20": ("Logistic-type, correlated", 20),
    "steps5": ("Steps and interactions", 5),
    "hetero5": ("Interactions, heteroskedastic", 5),
}


def render() -> str:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    lines = [
        "% AUTO-GENERATED by replication/scripts/generate_dml_designs_table.py",
        "\\begin{tabular}{@{}lrrrrrrrr@{}}",
        "\\toprule",
        " & & & \\multicolumn{3}{c}{Default learner} & "
        "\\multicolumn{3}{c}{Short-stacking} \\\\",
        "\\cmidrule(lr){4-6}\\cmidrule(l){7-9}",
        "Nuisance functions & \\(p\\) & \\(n\\) & Cover. & Bias/SD & SE/SD & "
        "Cover. & Bias/SD & SE/SD \\\\",
        "\\midrule",
    ]
    for name, (label, p) in LABELS.items():
        if name not in data["designs"] and os.environ.get("DML_DESIGNS_PARTIAL"):
            continue  # dry runs while the study is still going; never shipped
        d = data["designs"][name]
        a, b = d["default_learner"], d["short_stacking_default_roster"]
        n = f"{d['n']:,}".replace(",", "{,}")
        lines.append(
            f"{label} & {p} & {n} & {a['coverage']:.3f} & "
            f"{a['bias_over_sd']:+.2f} & {a['se_sd_ratio']:.2f} & "
            f"{b['coverage']:.3f} & {b['bias_over_sd']:+.2f} & "
            f"{b['se_sd_ratio']:.2f} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"FAIL -- {OUT.name} is stale; run generate_dml_designs_table.py")
            return 1
        print(f"OK -- {OUT.name} matches {SRC.name}")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"OK -- wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
