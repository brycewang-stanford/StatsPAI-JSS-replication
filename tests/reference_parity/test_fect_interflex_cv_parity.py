_FECT_FOLDS = _DIR / "fect_cv_folds_R.json"
_IFLX_FOLDS = _DIR / "interflex_cv_folds.json"
_IFLX_FOLDS_R = _DIR / "interflex_cv_folds_R.json"
REL_GIVEN_FOLD_IFLX = 1e-9  # measured 2.8e-13 (numpy lstsq vs R glm QR)
REL_GIVEN_FOLD_FECT = (
    1e-6  # measured 5.9e-8: same EM map / start / cv_tol, roundoff x iterations
)


@pytest.mark.skipif(not _FECT_FOLDS.exists(), reason="fect given-fold fixture missing")
@pytest.mark.parametrize("method", ["ife", "mc"])
def test_fect_scoring_matches_r_on_identical_folds(fect_df, method, monkeypatch):
    """Replay the 20 rolling folds fect built (set.seed(1)) and compare the
    fold x grid MSPE matrix and fect's pooled MSPE with R's, cell by cell."""
    from statspai.synth import _fect_cv as cvmod

    ref = json.loads(_FECT_FOLDS.read_text(encoding="utf-8"))
    folds = [
        (np.asarray(f["cv_id"], dtype=int) - 1, np.asarray(f["est_id"], dtype=int) - 1)
        for f in ref["folds"]
    ]
    monkeypatch.setattr(cvmod, "_rolling_folds", lambda *a, **k: folds)
    if method == "ife":
        run = _fect(fect_df, method="ife", cv=True, r_range=(0, 5))
        r_mat = np.asarray(ref["mspe_ife_by_fold"], dtype=float)
        pooled_r = np.asarray(ref["pooled_mspe_ife"], dtype=float)
    else:
        run = _fect(fect_df, method="mc", cv=True, lambda_grid=ref["lambda_grid"])
        r_mat = np.asarray(ref["mspe_mc_by_fold"], dtype=float)
        pooled_r = np.asarray(ref["pooled_mspe_mc"], dtype=float)
    cvi = run.model_info["cv"]
    assert cvi["n_scored_per_fold"] == [len(e) for _, e in folds]
    py_mat = cvi["fold_scores"].iloc[:, 1:].to_numpy(dtype=float)
    n_eval = py_mat.shape[0]  # the MC scan may stop before the end of the grid
    np.testing.assert_allclose(py_mat, r_mat[:n_eval], rtol=REL_GIVEN_FOLD_FECT)
    np.testing.assert_allclose(
        cvi["table"]["MSPE"].to_numpy(dtype=float),
        pooled_r[:n_eval],
        rtol=REL_GIVEN_FOLD_FECT,
    )


@pytest.mark.skipif(
    not (_IFLX_FOLDS.exists() and _IFLX_FOLDS_R.exists()),
    reason="interflex given-fold fixture missing",
)
def test_kernel_scoring_matches_r_on_identical_folds(iflx_df, monkeypatch):
    """Replay StatsPAI's fold assignments through interflex's own
    getError.CV (R) and compare the per-fold MSE / MAE / Num.Eff.Points at
    six bandwidths -- the five smallest (near-singular local fits, MSE up to
    ~460 on one fold) and a plateau point."""
    from statspai.regression import interflex as mod

    spec = json.loads(_IFLX_FOLDS.read_text(encoding="utf-8"))
    ref = json.loads(_IFLX_FOLDS_R.read_text(encoding="utf-8"))
    grid = np.asarray(ref["meta"]["grid"], dtype=float)
    idx = [int(i) for i in spec["grid_indices"]]
    for seed, fold_1based in spec["folds"].items():
        fold = np.asarray(fold_1based, dtype=int) - 1
        monkeypatch.setattr(mod, "_create_folds", lambda labels, k, rng, _f=fold: _f)
        run = sp.interflex(
            iflx_df,
            y="Y",
            d="D",
            x="X",
            z=["Z1"],
            estimator="kernel",
            cv=True,
            bw_grid=[float(grid[i]) for i in idx],
            random_state=0,
        )
        losses = run.model_info["cv"]["fold_losses"].iloc[:, 1:].to_numpy(dtype=float)
        table = run.model_info["cv"]["table"]
        for row, gi in enumerate(idx):
            r_row = ref["seeds"][seed][str(gi)]
            np.testing.assert_allclose(
                losses[row], r_row["mse"], rtol=REL_GIVEN_FOLD_IFLX
            )
            assert table["num_eff_points"].iloc[row] == np.mean(r_row["n_eff"])
            np.testing.assert_allclose(
                table["mae"].iloc[row], np.mean(r_row["mae"]), rtol=REL_GIVEN_FOLD_IFLX
            )
