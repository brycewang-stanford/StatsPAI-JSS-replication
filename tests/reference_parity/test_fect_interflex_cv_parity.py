def test_ife_deterministic_columns_match_r(ref, ife_runs):
    """sigma2 / IC / PC are full-data fits (no holdout): same EM map, same
    start, same cv_tol -> rel 1e-6 like the deterministic Track A rows."""
    r0 = next(iter(ref["fect_ife"].values()))
    tab = ife_runs[0].model_info["cv"]["table"]
    assert tab["r"].tolist() == r0["r"]
    for col, key in (("sigma2", "sigma2"), ("IC", "ic"), ("PC", "pc")):
        np.testing.assert_allclose(
            tab[col].to_numpy(), np.asarray(r0[key]), rtol=REL_DETERMINISTIC
        )


def test_ife_selection_matches_r_mode(ref, ife_runs):
    r_picks = [run["r_cv"] for run in ref["fect_ife"].values()]
    py_picks = [run.model_info["r_cv"] for run in ife_runs]
    _selection_gate(py_picks, r_picks, "fect ife r", adjacency_ok=False)


def test_ife_cv_curve_within_r_spread(ref, ife_runs):
    r_curves = np.array([run["mspe"] for run in ref["fect_ife"].values()])
    py_curves = np.array(
        [run.model_info["cv"]["table"]["MSPE"].to_numpy() for run in ife_runs]
    )
    _, sd_r, _ = _curve_gate(py_curves, r_curves, "fect ife MSPE")
    sel = ife_runs[0].model_info["r_cv"]
    sd_py = np.std(py_curves[:, sel], ddof=1)
    assert (
        1 / SPREAD_BAND <= sd_py / sd_r[sel] <= SPREAD_BAND
    ), f"fect ife: across-seed sd at r={sel} py {sd_py:.4f} vs R {sd_r[sel]:.4f}"


def test_ife_refit_equals_direct_call(fect_df, ife_runs):
    run = ife_runs[0]
    direct = _fect(fect_df, method="ife", r=run.model_info["r_cv"])
    assert run.estimate == direct.estimate
    assert (run.detail["att"].to_numpy() == direct.detail["att"].to_numpy()).all()


