def _curve_gate(py_curves: np.ndarray, r_curves: np.ndarray, label: str):
    """Four-sigma two-sample (Welch) z-gate at every grid point where both
    sides have values (R's MC scan stops early, so some tail points are NaN):
    ``|mean_py - mean_R| <= 4 sqrt(sd_R^2 / n_R + sd_py^2 / n_py)``. Each
    side's own across-seed variance enters because the fold draws are
    heavy-tailed at degenerate settings (a bandwidth of range/100 puts one
    fold in twenty at MSE > 100 on either side), and the given-fold tests
    below pin the scoring itself."""
    mean_r = np.nanmean(r_curves, axis=0)
    sd_r = np.nanstd(r_curves, axis=0, ddof=1)
    n_r_pt = np.sum(np.isfinite(r_curves), axis=0)
    mean_py = np.nanmean(py_curves, axis=0)
    sd_py = np.nanstd(py_curves, axis=0, ddof=1)
    n_py_pt = np.sum(np.isfinite(py_curves), axis=0)
    both = (n_r_pt >= max(3, r_curves.shape[0] // 2)) & (n_py_pt >= 2)
    assert both.sum() >= 3, f"{label}: too few common grid points"
    gate = Z_GATE * np.sqrt(
        sd_r**2 / np.maximum(n_r_pt, 1) + sd_py**2 / np.maximum(n_py_pt, 1)
    )
    diff = np.abs(mean_py - mean_r)
    bad = both & ~(diff <= gate)
    assert not bad.any(), (
        f"{label}: CV curve outside the {Z_GATE}-sigma across-seed gate at grid "
        f"points {np.where(bad)[0].tolist()}: |diff|={diff[bad]} gate={gate[bad]} "
        f"(R mean {mean_r[bad]}, R sd {sd_r[bad]}, py sd {sd_py[bad]})"
    )
    return mean_r, sd_r, mean_py


def _selection_gate(py_picks, r_picks, label: str, adjacency_ok: bool):
    """R's picks are unanimous for r and lambda on this fixture, so the
    modal pick is the gate; a one-step latitude is granted only where R's
    own seeds move across neighbouring grid points."""
    r_counts = Counter(r_picks)
    r_mode = r_counts.most_common(1)[0][0]
    py_mode = Counter(py_picks).most_common(1)[0][0]
    assert (
        py_mode == r_mode
    ), f"{label}: modal selection {py_mode} != R's modal {r_mode} ({r_counts})"
    allowed = set(r_picks)
    if adjacency_ok and len(allowed) > 1:
        allowed |= {r_mode - 1, r_mode + 1}
    for p in py_picks:
        assert (
            p in allowed
        ), f"{label}: selection {p} outside R's observed set {sorted(allowed)}"


def _plateau_gate(py_picks, r_picks, r_curves: np.ndarray, label: str):
    """For a criterion curve that is flat around its minimum (the bandwidth
    MSE here moves by < 1e-3 across six grid points while its across-seed sd
    is ~1.4e-2) R's own 20 seeds spread their pick over that plateau with no
    majority, so a modal gate is not justified. The measured gate is: every
    StatsPAI pick lies in the R plateau -- grid points whose R-mean loss is
    within one R across-seed sd of the R minimum -- and inside R's observed
    selection range widened by one grid step on each side."""
    mean_r = np.nanmean(r_curves, axis=0)
    sd_r = np.nanstd(r_curves, axis=0, ddof=1)
    plateau = set(np.where(mean_r - mean_r.min() <= sd_r)[0].tolist())
    lo, hi = min(r_picks) - 1, max(r_picks) + 1
    for p in py_picks:
        assert p in plateau, f"{label}: pick {p} outside R's plateau {sorted(plateau)}"
        assert (
            lo <= p <= hi
        ), f"{label}: pick {p} outside R's selection range [{lo}, {hi}]"
    assert set(r_picks) <= plateau, f"{label}: R's own picks leave the plateau"


