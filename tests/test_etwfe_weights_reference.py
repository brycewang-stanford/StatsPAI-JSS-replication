def _stata_factor(fit):
    ssc = fit.model_info["ssc"]
    n, k = ssc["n"], ssc["K"]
    return np.sqrt((n - k) / (n - (k - fit.model_info["n_cohorts"])))


def _split(spec):
    cgl, wl = spec.rsplit("_", 1)
    return cgl, wl


