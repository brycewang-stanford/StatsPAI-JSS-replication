def _emfx_rows(fit, agg_weights=None):
    """Every emfx aggregation as {statistic: (estimate, se)}."""
    out = {}
    simple = sp.etwfe_emfx(fit, type="simple", agg_weights=agg_weights)
    out["att"] = (float(simple.estimate), float(simple.se))
    for _, r in sp.etwfe_emfx(
        fit, type="event", agg_weights=agg_weights
    ).detail.iterrows():
        out[f"dyn_e{int(r['event_time'])}"] = (float(r["estimate"]), float(r["se"]))
    for _, r in sp.etwfe_emfx(
        fit, type="group", agg_weights=agg_weights
    ).detail.iterrows():
        out[f"group_{int(r['cohort'])}"] = (float(r["estimate"]), float(r["se"]))
    for _, r in sp.etwfe_emfx(
        fit, type="calendar", agg_weights=agg_weights
    ).detail.iterrows():
        out[f"cal_{int(r['calendar_time'])}"] = (float(r["estimate"]), float(r["se"]))
    return out


