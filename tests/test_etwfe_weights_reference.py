@pytest.mark.parametrize("app,cgl", PANEL_CASES)
def test_group_rows_agree_between_rules_for_unit_constant_weights(rows, app, cgl):
    est_rule = rows[((app, cgl, "wt"), "estimation")]
    unit_rule = rows[((app, cgl, "wt"), "unit")]
    groups = [k for k in est_rule if k.startswith("group_")]
    assert len(groups) == CFG[app]["n_cohorts"]
    for k in groups:
        # A cohort's post cells all carry the same weight total, so the
        # within-cohort average is the same under both rules (R == Stata).
        assert est_rule[k][0] == pytest.approx(unit_rule[k][0], rel=1e-12)
        assert est_rule[k][1] == pytest.approx(unit_rule[k][1], rel=1e-12)
    mixed = [k for k in est_rule if not k.startswith("group_")]
    n_diff = sum(
        abs(est_rule[k][0] - unit_rule[k][0]) > 1e-6 * abs(unit_rule[k][0])
        for k in mixed
    )
    # Aggregates that mix cohorts differ (all but the single-cohort cells).
    assert n_diff >= len(mixed) // 2


