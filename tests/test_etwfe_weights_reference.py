"""Reference parity: ``sp.etwfe(weights=...)`` vs Stata ``jwdid [pw=]`` and R
``etwfe(weights=)`` on two locked panels.

Panels
------
* castle -- Cheng & Hoekstra castle-doctrine panel,
  ``sp.datasets.castle_doctrine(event_time=True)`` (50 states x 2000-2010,
  cohorts 2005-2009, 29 never-treated states), weight ``popwt``.
* divorce -- the Stevenson-Wolfers no-fault-divorce panel behind Goodman-
  Bacon's ``bacon_example.dta`` (``tests/fixtures/divorce_no_fault_panel.csv``,
  byte-identical to the DiD reconciliation study's locked CSV, SHA-256
  ``179d5d7a...``).  The cohort estimators run on the 41 states with
  ``always_treated == 0`` (1964-1996, 12 cohorts 1969-1985, weight ``weight``).

Both weights are constant within unit, so the two aggregation rules below
agree on the ``group`` rows and differ on ``simple`` / ``event`` /
``calendar``.

References (copied from ``Paper-DiD-JAE/replication/applications/<app>/
results/<app>_Stata.json`` / ``<app>_R.json``, rows ``estimator == "etwfe"``)

* Stata 18, jwdid v2.2 (reghdfe 6.13.1)::

      jwdid y [pw=w], ivar(unit) tvar(year) gvar(cohort) [never]
      estat simple | event | group | calendar

  ``estat`` runs ``margins`` on the ``[pw=]`` estimation sample, so a
  cohort-by-period cell ``(g, t)`` enters every aggregate with the **sum of
  the estimation weights over its treated observations**,
  ``W_{g,t} = sum_{i in g} w_{i,t}`` -- ``sp.etwfe(agg_weights='estimation')``,
  the default.  Under never-treated controls this makes the ``simple``
  aggregate identical to the weighted Callaway--Sant'Anna simple ATT
  (divorce: -13.26894340282183 on both, an estimand-level identity), which
  is why it is the default.

* R 4.5.2, etwfe 0.6.2, fixest 0.14.0, marginaleffects 0.32.0::

      etwfe::etwfe(fml = y ~ 0, tvar = year, gvar = cohort, data = dat,
                   vcov = ~unit, cgroup = "never" | "notyet", weights = ~w)
      etwfe::emfx(e, type = "simple" | "event" | "group" | "calendar")

  ``emfx`` evaluates ``marginaleffects::slopes`` with ``wts = 1`` per treated
  row, so ``W_{g,t} = n_{g,t}`` and the estimation weights only enter the
  regression -- ``sp.etwfe(agg_weights='unit')``.

Standard errors: both sides apply ``G / (G - 1) * (n - 1) / (n - K)`` to the
same weighted cluster-robust covariance; fixest's ``K`` counts the cohort and
period fixed-effect levels on top of the cells, reghdfe drops the unit effects
as nested in the cluster, so ``se_Stata = se_R * sqrt((n - K_R) / (n - K_Stata))``
with ``K_R - K_Stata`` = number of treated cohorts (castle 66/61 never, 36/31
not-yet; divorce 429/417 and 303/291).  StatsPAI reports R's ``K``.  R's
*reported* SEs carry marginaleffects' finite-difference Jacobian noise (up to
3.3e-6 relative on divorce, 5.1e-7 on castle), hence the looser R-side SE
tolerance; the Stata reconstruction uses analytic derivatives and is pinned at
1e-9 (observed max 1.9e-12).
"""

